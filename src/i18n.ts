export type TKey = keyof (typeof dict)['nl'];

function loadLang(): Lang {
  try {
    const v = localStorage.getItem('carcity.lang');
    if (v === 'nl' || v === 'en') return v;
  } catch { /* storage blocked */ }
  return 'nl'; // Dutch by default
}

