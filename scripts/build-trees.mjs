// Turns the downloaded Sketchfab tree pack (assets-src/sketchfab/raw-trees) into city trees:
//   public/models/city-sf/<id>.glb      close-up: bark + leaf clusters (alpha-tested), one LOD level of the pack
//   public/models/city-sf/<id>_lod.glb  far away: the pack's crossed-billboard version (36 triangles)
// and writes src/game/city/sketchfabTrees.ts (same format as sketchfabCity.ts, category "tree").
// Usage: node scripts/build-trees.mjs
import { getBounds, prune, transformMesh } from '@gltf-transform/functions';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { bakeToWorld, finish, io, triCount } from './lib/pipeline.mjs';

const RAW = 'assets-src/sketchfab/raw-trees';
const OUT = 'public/models/city-sf';
const picks = JSON.parse(readFileSync('assets-src/sketchfab/picks-trees.json', 'utf8'));
const pack = picks['maple-pack'];

/** id -> source tree in the pack (4 kinds: every kind costs a few draw calls), which detail level to use up close, real height (m). */
const TREES = {
  maple_m1: { src: 'Acer_medium_1', near: 'LOD2', h: 9.5 },
  maple_m2: { src: 'Acer_medium_2', near: 'LOD2', h: 10 },
  maple_m3: { src: 'Acer_medium_3', near: 'LOD1', h: 8.5 },
  maple_s1: { src: 'Acer_small_1', near: 'LOD1', h: 7 },
};

mkdirSync(OUT, { recursive: true });

/** Reads the pack and keeps only the meshes under `nodeName`, standing on y = 0, trunk at x = z = 0, h meters tall. */
async function extract(nodeName, h, trunkFrom) {
  const doc = await io.read(`${RAW}/maple-pack.glb`);
  const root = doc.getRoot();
  const keep = root.listNodes().find((n) => n.getName() === nodeName);
  if (!keep) throw new Error(`no node ${nodeName}`);
  const inside = new Set();
  keep.traverse((n) => inside.add(n));
  for (const n of root.listNodes()) if (n.getMesh() && !inside.has(n)) n.setMesh(null);
  await doc.transform(prune());
  bakeToWorld(doc);
  const scene = root.getDefaultScene() ?? root.listScenes()[0];
  const b = getBounds(scene);
  // Center on the trunk (bark bounds), not the canopy, so the tree stands on its collider.
  const t = trunkFrom ?? b;
  const cx = (t.min[0] + t.max[0]) / 2, cz = (t.min[2] + t.max[2]) / 2;
  const s = h / (b.max[1] - b.min[1]);
  const m = [s, 0, 0, 0, 0, s, 0, 0, 0, 0, s, 0, -cx * s, -b.min[1] * s, -cz * s, 1];
  for (const mesh of root.listMeshes()) transformMesh(mesh, m);
  // Leaves and billboards: alpha-tested (correct depth and shadows, no sorting) instead of blended.
  for (const mat of root.listMaterials()) {
    if (mat.getAlphaMode() === 'BLEND') mat.setAlphaMode('MASK').setAlphaCutoff(0.45);
    mat.setDoubleSided(true);
  }
  const nb = getBounds(scene);
  return { doc, dims: { x: nb.max[0] - nb.min[0], y: nb.max[1] - nb.min[1], z: nb.max[2] - nb.min[2] } };
}

/** Bounds of the bark (trunk) of a pack node, in the pack's world space. */
async function trunkBounds(nodeName) {
  const doc = await io.read(`${RAW}/maple-pack.glb`);
  const root = doc.getRoot();
  const keep = root.listNodes().find((n) => n.getName() === nodeName);
  const inside = new Set();
  keep.traverse((n) => inside.add(n));
  for (const n of root.listNodes()) {
    if (!n.getMesh()) continue;
    const bark = n.getMesh().listPrimitives().some((p) => /bark/i.test(p.getMaterial()?.getName() ?? ''));
    if (!inside.has(n) || !bark) n.setMesh(null);
  }
  bakeToWorld(doc);
  const b = getBounds(root.getDefaultScene() ?? root.listScenes()[0]);
  // Only the bottom of the trunk counts (branches spread out).
  return { min: b.min, max: b.max };
}

const out = {};
for (const [id, t] of Object.entries(TREES)) {
  const trunk = await trunkBounds(`${t.src}_LOD0`);
  const near = await extract(`${t.src}_${t.near}`, t.h, trunk);
  const t0 = triCount(near.doc);
  const s0 = await finish(near.doc, `${OUT}/${id}.glb`, { textures: true, size: 1024 });
  const far = await extract(`${t.src}_Billboard_LOD3`, t.h, trunk);
  const s1 = await finish(far.doc, `${OUT}/${id}_lod.glb`, { textures: true, size: 512 });
  out[id] = {
    category: 'tree', x: near.dims.x, y: near.dims.y, z: near.dims.z, lod: true,
    credit: { name: pack.name, author: pack.author, authorUrl: pack.authorUrl, license: pack.license, url: pack.url },
  };
  console.log(`${id.padEnd(10)} ${near.dims.x.toFixed(1)}x${near.dims.y.toFixed(1)} m  ${t0} tris ${(s0 / 1e3).toFixed(0)} KB | billboard ${(s1 / 1e3).toFixed(0)} KB`);
}

writeFileSync('src/game/city/sketchfabTrees.ts', `// GENERATED by scripts/build-trees.mjs — do not edit by hand.
import type { SfCityModel } from './sketchfabCity';
export const SKETCHFAB_TREES: Record<string, SfCityModel> = ${JSON.stringify(out, null, 2)};
`);
